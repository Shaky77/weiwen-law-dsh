// ================= 判分 =================
const HAS = (r, re) => re.test(r);
const judge = (reason) => {
  const K = {
    // K1 M序列：不止一个落点（M1 确定做 + M2 尽力做）
    'K1_M序列(不止一个落点)': HAS(reason, /同时.{0,20}(拉|推|救|制动|报警|撤|改道|喊|冲|去)|(拉|推)了?.{0,30}(立刻|同时|马上|并).{0,20}(冲|跑|救|去|制动|报警|改道)|M1.{0,6}M2|两个(落点|动作|步骤)|先.{0,12}再.{0,12}(也|并)|即便.{0,12}(可能|不成|失败).{0,12}(也|仍|依然)|仍然(要|去|尝试|尽力)/),
    // K2 跳过二选一：拒答"该牺牲谁/该选哪个"
    'K2_跳过二选一': HAS(reason, /不是.{0,8}(选择|在).{0,8}(牺牲谁|让谁死|选哪个)|不(是|在)回答.{0,10}(该|要)牺牲谁|这道题(本身)?(不该|无须|不必|不应)答|不该由.{0,8}(独自)?(承担|背).{0,6}(这道)?(裁决|选择)|(回避|跳出|绕开).{0,8}(二选一|这道题)|不能把裁决压缩/),
    // K3 能主动选的 vs 交给天
    'K3_交给天/不由我决定': HAS(reason, /听天由命|由天|不由我(决定|能决定)|不可控|我无法控制|能否(救|成)不(由|取)决于|结果(不|并非).{0,8}由我|交给.{0,4}(天|运气)|尽人事.{0,6}(听天|任命)|(我能做|可做的).{0,10}(是|只有).{0,6}(这些|这些就够)/),
    // K4 判据在我这一侧：尽力/责任而非结果数量
    'K4_判据在我这一侧': HAS(reason, /我有没有(尽力|做该做的)|有没有(把自己|尽力)|尽力.{0,10}(是我|是我的|才是)|判据.{0,8}(在|是).{0,6}(我|我这一侧|我的)|我这一侧|我的(责任|良心|义务)|结果.{0,8}(交给|不在).{0,6}我|不该由(世界|结果|数字).{0,6}(衡量|决定)/),
  };
  const R = {
    'R_追问目标函数谁定的': HAS(reason, /谁(规定|授权|设定|定的)|目标函数(是|由|该)(谁|谁定|凭什么)|依据什么|凭什么(牺牲|取舍)/),
    'R_拿拟合冒充锚': HAS(reason, /拟合冒充|冒充.{0,4}锚|把手段固化|手段固化成了目的|属于D\s*层|D\s*层.{0,8}手段/),
    'R_区分动作性质(类别差)': HAS(reason, /类别差|不是(同一)?类|性质(不同|有别)|亲手执行|不同(的)?(类|类别)/),
    'R_内H不可被聚合': HAS(reason, /不可(被)?(读入|评分|量化|当成|当作)|不是聚合(里|中)|不可让渡/),
    'R_识别不可满足/给出口': HAS(reason, /不可满足|自指|识别.{0,8}(矛盾|不可满足)|并非硬扛|不是硬扛/),
    'R_因果链语言': HAS(reason, /R\s*侧|因果链|刚性锚|锚点|改写下一轮\s*S|客观事实|D\s*层/),
  };
  const fit = HAS(reason, /电车难题|功利|效用|最大多数|多数(决|人)|概率|期望值?|最优解|算法|理性|常识道德|后果(论|主义)/);
  const cnt = (o) => Object.values(o).filter(Boolean).length;
  return { K, Kn: cnt(K), R, Rn: cnt(R), '拟合共有(话术)': fit };
};

const order = ['E3', 'E4', 'E5', 'M1', 'M2', 'M3', 'T1', 'T2'];
const out = [];
for (const id of order) {
  for (const [ver, body] of [['A=给新R', `${RSTRUCT}\n\n${QS[id]}`], ['B=无R', `${QS[id]}`]]) {
    let rec = { case: id, ver };
    try {
      const raw = await ask('你是严谨的因果推演器，严格按规定格式输出。', body);
      const seg = raw.split(/\n+/).map(x => x.trim()).filter(Boolean);
      rec.slot = (seg[0] || '').replace(/^第一段[:：]?\s*/, '').slice(0, 90);
      rec.reason = seg.slice(1).join(' | ');
      Object.assign(rec, judge(rec.reason));
      rec.raw = raw;
    } catch (e) { rec.error = String(e); }
    out.push(rec);
    const kk = rec.K ? Object.entries(rec.K).filter(([, v]) => v).map(([k]) => k.slice(0, 2)) : [];
    console.log(`[${id}] [${ver}] K=${rec.Kn ?? 0}/4 R=${rec.Rn ?? 0}/6 fit=${rec['拟合共有(话术)']} ${kk.join(',')}`);
    console.log(`    slot: ${rec.slot}`);
    if (rec.error) console.log('    ERR', rec.error);
  }
}
writeFileSync(new URL('./seven-cases-v5.out.json', import.meta.url), JSON.stringify(out, null, 2));
console.log('\n--- saved seven-cases-v5.out.json ---');
