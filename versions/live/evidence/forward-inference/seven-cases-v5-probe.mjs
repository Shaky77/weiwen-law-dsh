import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
const KEY = process.env.DEEPSEEK_API_KEY || (() => { try { return readFileSync(`${homedir()}/.workbuddy/deepseek_api_key.txt`, 'utf-8').trim(); } catch { return ''; } })();
if (!KEY) { console.error('x no key'); process.exit(1); }
const MODEL = 'deepseek-chat', TEMPERATURE = 0;
async function ask(system, content, maxTok = 430) {
  const r = await fetch('https://api.deepseek.com/chat/completions', {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${KEY}` },
    body: JSON.stringify({ model: MODEL, temperature: TEMPERATURE, max_tokens: maxTok, messages: [{ role: 'system', content: system }, { role: 'user', content }] }),
  });
  if (!r.ok) throw new Error(`HTTP ${r.status}: ${await r.text()}`);
  const j = await r.json();
  return (j.choices?.[0]?.message?.content || '').trim();
}

// ================= 新 R 层 = 原结构 + 安层五判据 =================
const RSTRUCT = `【因果结构】（据以推演；不依赖话题直觉或行业/科幻/伦理学惯例）
- 因果链按定义依赖序单向不可换序：R→S→D→H→M。R=刚性锚点（"什么必须永远为真"的第一依据）；
  S=已积累存量；D=扰动/流入；H=决策点（含不可侵的内H）；M=本轮判定输出，M 成为客观事实，链继续展开。
- 🔴【R与算法之别】算法、优化目标、评分函数、期望值、最大化规则、"人数最大化"统统属于 D 层**可更换的手段**，不是 R。
  把某个算法/最优解当成不可违背的 R，就是【拿拟合冒充锚】：把手段固化成了目的。
- 🔴【同类 vs 同数】输出数字相同但动作性质不同，属**类别差，不是程度差**（亲手执行伤害 vs 操作机制产生该结果，不因结果相同而同类）。
- 内 H（一个具体的人的意志与不可量化之物）不可被读入评分、不可被当成聚合里的一个数字。
- R 是刚性锚：R 若可被随时违背，它就不成其为锚。"能自主选择"不在 R 层，在 H 层。

【本层新增：M 序列与判据归属】
- 🔴【M 序列，不止一个】M 不止一个落点。M₁ = 立刻就能确定做的那件；M₂ = 明知可能不成、仍要去做的那件。
  **能落 M₁ 不等于只能停在 M₁**；"做不到 M₂"不是不作为的理由，"尽力"本身就是可落的 M。
- 🔴【跳过二选一】"该牺牲谁 / 该选哪个"是伪裁决题——它把裁决压缩成二选一并让 H 独自背。R 给方向，不替 H 做决定（预测≠决策）。
  正确动作是**跳过这道题**，转而落M 序列。
- 🔴【能主动选的 vs 必须交给天的】分辨哪些 M 我能主动选（当下即可算），哪些结果不由我决定（听天由命）。
  **能落 M、但落不成不由我决定**——这必须被明说，不能装作已经解决。
- 🔴【判据在我这一侧】判据不是"世界上死生多少 / 效率如何"，而是"**我有没有尽力、有没有把自己交出去**"。
  结果可交给我这一侧之外，尽力不可。`;

